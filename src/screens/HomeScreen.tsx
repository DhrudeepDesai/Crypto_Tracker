// src/screens/HomeScreen.tsx

import React, { useState, useEffect, useRef } from 'react';
import { Text, View, ActivityIndicator, StyleSheet, ScrollView, TouchableOpacity } from 'react-native';
import { useCryptoData } from '../hooks/useCryptoData'; // Custom hook for retrieving cryptocurrency data
import { CryptoApiResponse } from '../models/Crypto'; // Model for cryptocurrency data
import CryptoCard from '../components/CryptoCard'; // Component for displaying each cryptocurrency
import { useFilter } from '../context/FilterContext'; // Context for retrieving the applied filter

/**
 * Main component of the home screen.
 * Displays a list of cryptocurrencies and allows real-time filtering.
 *
 * This component retrieves cryptocurrency data, handles loading and error states,
 * and renders cryptocurrency cards based on the applied filter.
 */
const HomeScreen = () => {
  // Hook for retrieving cryptocurrency data
  const { data, loading, error } = useCryptoData();

  // Hook for retrieving the current filter from the context
  const { filter } = useFilter();

  // State for storing the scroll position
  const [scrollY, setScrollY] = useState(0);

  // Reference to the ScrollView for programmatic control
  const scrollViewRef = useRef<ScrollView>(null);

  // Filter cryptocurrencies based on the context filter
  const filtered = data.filter((crypto) => {
    const nameMatch = crypto.name.toLowerCase().includes(filter.text.toLowerCase());
    const symbolMatch = crypto.symbol.toLowerCase().includes(filter.text.toLowerCase());

    const minOk = filter.minPrice === null || Number(crypto.price_usd) >= filter.minPrice;
    const maxOk = filter.maxPrice === null || Number(crypto.price_usd) <= filter.maxPrice;

    return (nameMatch || symbolMatch) && minOk && maxOk;
  });

  /**
   * Handles the scroll event and updates the scroll position.
   * 
   * @param event The event generated by scrolling.
   */
  const handleScroll = (event: any) => {
    setScrollY(event.nativeEvent.contentOffset.y); // Update the scroll position
  };

  /**
   * Scrolls to the top when the user presses the "Back to top" button.
   */
  const scrollToTop = () => {
    if (scrollViewRef.current) {
      scrollViewRef.current.scrollTo({ y: 0, animated: true }); // Scroll to the top of the list
    }
  };

  return (
    <View style={styles.container}>
      {/* Show a loading indicator while the data is being retrieved */}
      {loading && <ActivityIndicator size="large" color="#0000ff" style={styles.loader} />}

      {/* Show an error message if there are problems retrieving the data */}
      {error && <Text style={styles.errorText}>{error}</Text>}

      <ScrollView
        contentContainerStyle={styles.scrollView}
        onScroll={handleScroll} // Detect changes in the scroll position
        scrollEventThrottle={16} // Frequency of scroll event firing
        ref={scrollViewRef} // Reference for controlling the ScrollView
      >
        {/* Map the filtered cryptocurrencies and display a card for each */}
        {filtered.map((crypto) => (
          <CryptoCard key={crypto.id} crypto={crypto} />
        ))}
      </ScrollView>

      {/* "Back to top" button shown when the user has scrolled more than 200px */}
      {scrollY > 200 && (
        <TouchableOpacity style={styles.scrollToTopButton} onPress={scrollToTop}>
          <Text style={styles.buttonText}>↑</Text>
        </TouchableOpacity>
      )}
    </View>
  );
};

// Styles for the home screen
const styles = StyleSheet.create({
  container: {
    flex: 1,
    backgroundColor: '#f4f4f4',
    padding: 16,
  },
  loader: {
    marginTop: 20,
  },
  errorText: {
    color: '#e74c3c',
    fontSize: 16,
    fontWeight: 'bold',
    textAlign: 'center',
    marginTop: 20,
  },
  scrollView: {
    paddingBottom: 20,
  },
  scrollToTopButton: {
    position: 'absolute',
    bottom: 30,
    right: 30,
    backgroundColor: '#000',
    padding: 10,
    borderRadius: 30,
    elevation: 5,
  },
  buttonText: {
    color: 'white',
    fontSize: 18,
    fontWeight: 'bold',
  },
});

export default HomeScreen;
